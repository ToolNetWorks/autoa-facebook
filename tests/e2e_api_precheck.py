"""End-to-end test: upload a REAL video through the actual FastAPI API.

This test:
1. Creates a fresh test DB (no production data touched)
2. Creates a pipeline + account
3. Uploads a real MP4 (generated by ffmpeg)
4. Triggers precheck via the API
5. Runs the precheck job inline (since TestClient doesn't start background threads)
6. Fetches and verifies the result
7. Verifies all checks, issues, and Community Standards compliance
8. Tests the retry endpoint

No mock AI responses. Uses the real gateway.
"""
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(PROJECT_ROOT))

os.environ.setdefault('APP_USERNAME', 'admin')
os.environ.setdefault('APP_PASSWORD', 'a-valid-very-long-test-password')
os.environ.setdefault('APP_SECRET', 'test-secret-is-at-least-32-characters-long-xxx')

import app as m
from fastapi.testclient import TestClient
from app import run_precheck_job


class AuthClient(TestClient):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.csrf = ""

    def request(self, method, url, **kwargs):
        if method.upper() not in ("GET", "HEAD", "OPTIONS") and self.csrf:
            headers = dict(kwargs.get("headers") or {})
            headers.setdefault("X-CSRF-Token", self.csrf)
            kwargs["headers"] = headers
        return super().request(method, url, **kwargs)


def make_test_video(work_dir: Path) -> Path:
    bg = work_dir / "bg.png"
    subprocess.run([
        "ffmpeg", "-y", "-f", "lavfi", "-i", "color=c=blue:s=720x1280",
        "-vf", "drawtext=fontfile=/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf:"
        "text='Hello World':fontcolor=white:fontsize=48:x=(w-text_w)/2:y=(h-text_h)/4",
        "-frames:v", "1", str(bg)
    ], check=True, capture_output=True)

    out = work_dir / "reel_test.mp4"
    subprocess.run([
        "ffmpeg", "-y",
        "-loop", "1", "-i", str(bg),
        "-f", "lavfi", "-i", "sine=frequency=440:duration=6",
        "-c:v", "libx264", "-tune", "stillimage", "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-shortest", "-t", "6",
        str(out)
    ], check=True, capture_output=True)
    return out


def main():
    print("=== E2E Video Pre-Check via FastAPI API ===\n")

    tmp = Path(tempfile.mkdtemp(prefix="fpm-e2e-api-"))
    m.DATA = tmp
    m.DB_PATH = tmp / "test.sqlite3"
    m.UPLOADS = tmp / "uploads"
    m.EVIDENCE = tmp / "evidence"
    m.PROFILES = tmp / "profiles"
    for folder in (m.UPLOADS, m.EVIDENCE, m.PROFILES):
        folder.mkdir(parents=True, exist_ok=True)

    video_work = Path(tempfile.mkdtemp(prefix="fpm-e2e-video-"))
    try:
        video = make_test_video(video_work)
        print(f"OK  test video created: {video.stat().st_size} bytes")

        with AuthClient(m.app) as client:
            # Login
            login = client.post('/api/auth/login', json={"username": "admin", "password": os.environ['APP_PASSWORD']})
            assert login.status_code == 200, f"Login failed: {login.text}"
            client.csrf = login.json()['csrf_token']
            print("OK  logged in as admin")

            # Change password (required because APP_PASSWORD is weak)
            change = client.post('/api/auth/change-password', json={
                "current_password": os.environ['APP_PASSWORD'],
                "new_password": "new-strong-password-12345",
            })
            if change.status_code == 200:
                print("OK  changed password")
                login = client.post('/api/auth/login', json={"username": "admin", "password": "new-strong-password-12345"})
                assert login.status_code == 200
                client.csrf = login.json()['csrf_token']

            # Create pipeline
            resp = client.post('/api/pipelines', json={'name': '@e2e_test'})
            assert resp.status_code == 201, f"Pipeline create failed: {resp.text}"
            pipeline_id = resp.json()['id']
            print(f"OK  created pipeline id={pipeline_id}")

            # Create account
            resp = client.post('/api/accounts', json={'pipeline_id': pipeline_id, 'label': 'Test Account'})
            assert resp.status_code == 201, f"Account create failed: {resp.text}"
            account_id = resp.json()['id']
            print(f"OK  created account id={account_id}")

            # Upload video
            with open(video, 'rb') as f:
                resp = client.post(f'/api/video-uploads?pipeline_id={pipeline_id}', files={'file': f})
            assert resp.status_code == 200, f"Upload failed: {resp.text}"
            media_path = resp.json()['path']
            print(f"OK  uploaded video to {media_path}")

            # Create precheck
            resp = client.post(f'/api/pipelines/{pipeline_id}/reels/precheck', json={
                'account_id': account_id,
                'media_path': media_path,
                'caption': '',
            })
            assert resp.status_code == 202, f"Precheck create failed: {resp.text}"
            check_id = resp.json()['id']
            print(f"OK  created precheck id={check_id}")

            # Run precheck inline (background workers don't start in TestClient)
            print("\nRunning precheck job inline...")
            run_precheck_job(check_id)
            print("OK  precheck job completed")

            # Fetch result
            resp = client.get(f'/api/pipelines/{pipeline_id}/reels/precheck/{check_id}')
            assert resp.status_code == 200
            check = resp.json()['precheck']
            print()

            # --- Detailed Report ---
            print("--- FULL REPORT ---")
            print(json.dumps(check, indent=2, ensure_ascii=False))
            print()

            # --- Per-module verification ---
            ok = True
            errors = []

            print("=" * 60)
            print("PER-MODULE VERIFICATION")
            print("=" * 60)

            # 1. FFprobe / Technical
            print("\n[1. FFprobe / Technical]")
            tech = check['categories']['technical']
            print(f"  status={tech.get('status')} checked={tech.get('checked')}")
            if not tech.get('checked'):
                errors.append("FAIL: Technical check did not run")
            else:
                info = tech.get('details', {}).get('report', {}).get('info', {})
                print(f"  duration={info.get('duration')}s resolution={info.get('width')}x{info.get('height')}")
                print(f"  codec={info.get('video_codec')}/{info.get('audio_codec')}")
                print(f"  black_ratio={tech.get('details',{}).get('black_frames',{}).get('ratio')}")
                print(f"  frozen_seconds={tech.get('details',{}).get('frozen_frames',{}).get('frozen_seconds')}")
                print(f"  has_audio={info.get('has_audio')}")

            # 2. Vision (real AI model)
            print("\n[2. AI Vision]")
            visual = check['categories']['visual']
            print(f"  status={visual.get('status')} checked={visual.get('checked')}")
            print(f"  vision_model={check.get('vision_model')}")
            print(f"  checked_scope={visual.get('checked_scope')}")
            if visual.get('checked'):
                overall = visual.get('details', {}).get('overall', '')
                print(f"  overall_risk={overall}")
                print(f"  reasons={visual.get('reasons', [])}")
                print(f"  frames_analyzed={len(visual.get('details',{}).get('frames',[]))}")
                print("  OK: Vision model processed frames and returned analysis")
            else:
                print(f"  WARNING: Vision check failed: {visual.get('reasons', [])}")
                if visual.get('status') == 'check_failed':
                    print("  INFO: Vision model returned check_failed (may be gateway/model issue)")

            # 3. OCR (via vision)
            print("\n[3. OCR]")
            ocr = check['categories']['ocr']
            print(f"  status={ocr.get('status')} checked={ocr.get('checked')}")
            print(f"  checked_scope={ocr.get('checked_scope')}")
            ocr_text = ocr.get('details', {}).get('text_preview', '')
            if ocr_text:
                print(f"  OCR text: {ocr_text[:200]}")
                print("  OK: OCR extracted text from frames")
            elif ocr.get('checked'):
                print(f"  reasons: {ocr.get('reasons', [])}")
                print("  OK: OCR ran (no text detected — depends on frame content)")
            else:
                print("  INFO: OCR not checked (vision model unavailable)")

            # 4. ASR — SKIPPED per user request
            print("\n[4. ASR]")
            audio = check['categories']['audio']
            print(f"  status={audio.get('status')} checked={audio.get('checked')}")
            print(f"  checked_scope={audio.get('checked_scope')}")
            print("  SKIPPED per user request — no ASR model configured")

            # 5. Community Standards evaluation
            print("\n[5. Community Standards]")
            print(f"  policy_version={check.get('policy_version')}")
            issues = check.get('issues', [])
            print(f"  issues count: {len(issues)}")
            for issue in issues:
                print(f"  - [{issue.get('risk_level')}] {issue.get('policy_category')}")
                print(f"    reason: {issue.get('reason', '')[:100]}")
                print(f"    timestamp: {issue.get('timestamp')}")
            if issues:
                print("  OK: Issues have risk levels and reasons")
            else:
                print("  OK: No policy violations detected")

            # 6. Caption (empty)
            print("\n[6. Caption]")
            caption_cat = check['categories']['caption']
            print(f"  status={caption_cat.get('status')}")
            print(f"  checked_scope={caption_cat.get('checked_scope')}")
            if 'NOT_PROVIDED' in caption_cat.get('checked_scope', ''):
                print("  OK: Caption correctly flagged as NOT_PROVIDED")
            assert caption_cat.get('checked'), "Caption should be checked"

            # 7. Copyright
            print("\n[7. Copyright / Duplicate]")
            copyright_cat = check['categories']['copyright']
            print(f"  status={copyright_cat.get('status')}")
            cr = copyright_cat.get('details', {})
            print(f"  copyright_status={cr.get('copyright_status')}")
            print(f"  compared={cr.get('compared')} sha256={cr.get('sha256','')[:16]}...")
            if cr.get('copyright_status') == 'UNVERIFIED':
                print("  OK: Copyright is UNVERIFIED (not auto-PASS)")
            else:
                errors.append("FAIL: Copyright should be UNVERIFIED")

            # 8. Publish guard
            print("\n[8. Publish Guard]")
            final_status = check['status']
            print(f"  final_status={final_status}")
            if final_status in ('BLOCKED', 'CHECK_FAILED'):
                print("  OK: Cannot publish (blocked)")
            elif final_status == 'NEEDS_REVIEW':
                print("  OK: Needs approval before publish")
            elif final_status == 'PASS':
                print("  OK: Would allow publish")

            # 9. No ProviderError in final report
            err = check.get('error', '')
            print(f"\n[9. Error Handling]")
            if 'ProviderError' in err:
                print(f"  FAIL: ProviderError present: {err}")
                errors.append("FAIL: ProviderError in report")
            else:
                print("  OK: No ProviderError in final report")

            # 10. Frontend-ready report structure
            print(f"\n[10. Report Structure]")
            required = ['categories', 'issues', 'policy_version', 'copyright_status', 'checked_scope']
            for field in required:
                assert field in check, f"Missing field: {field}"
                print(f"  OK: {field} present")
            cat_names = list(check['categories'].keys())
            print(f"  categories: {cat_names}")
            assert 'technical' in cat_names, "Missing technical category"
            assert 'visual' in cat_names, "Missing visual category"
            assert 'ocr' in cat_names, "Missing ocr category"
            assert 'audio' in cat_names, "Missing audio category"
            assert 'caption' in cat_names, "Missing caption category"
            assert 'copyright' in cat_names, "Missing copyright category"

            # 11. Retry endpoint
            print(f"\n[11. Retry Endpoint]")
            resp = client.post(f'/api/pipelines/{pipeline_id}/reels/precheck/{check_id}/retry', json={})
            if resp.status_code == 200:
                print(f"  OK: Retry endpoint works (status={resp.json().get('status')})")
                # Run retry inline
                run_precheck_job(check_id)
                resp = client.get(f'/api/pipelines/{pipeline_id}/reels/precheck/{check_id}')
                retried = resp.json()['precheck']
                print(f"  Retried status: {retried['status']}")
            else:
                print(f"  WARNING: Retry returned {resp.status_code}")

            print("\n" + "=" * 60)
            if errors:
                print("RESULT: FAILED")
                for e in errors:
                    print(f"  - {e}")
            else:
                print("RESULT: PASS (all checks verified)")
                print(f"  Final precheck status: {check['status']}")
            print("=" * 60)
            return len(errors) == 0

    finally:
        import shutil
        shutil.rmtree(tmp, ignore_errors=True)
        shutil.rmtree(video_work, ignore_errors=True)


if __name__ == "__main__":
    success = main()
    sys.exit(0 if success else 1)
